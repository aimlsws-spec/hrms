import { useState, useEffect, useCallback } from 'react'
import { payslipApi }          from '../../api/payslipApi'
import type { PayslipSummary } from '../../api/payslipApi'

const now = new Date()
const defaultMonth = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`

function fmt(n: number) {
  return '₹' + n.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

function initials(name: string) {
  return name.split(' ').map(w => w[0]).slice(0, 2).join('').toUpperCase()
}

export default function AccountantPayslipsPage() {
  const [monthYear,  setMonthYear]  = useState(defaultMonth)
  const [rows,       setRows]       = useState<PayslipSummary[]>([])
  const [loading,    setLoading]    = useState(true)
  const [error,      setError]      = useState<string | null>(null)
  const [viewing,    setViewing]    = useState<string | null>(null)
  // Tracks which employee IDs have no generated salary slip for the current month
  const [notGenerated, setNotGenerated] = useState<Set<string>>(new Set())

  const load = useCallback(async (my: string) => {
    setLoading(true)
    setError(null)
    setNotGenerated(new Set())
    try {
      const [year, month] = my.split('-').map(Number)
      const { data } = await payslipApi.getAll(month, year)
      setRows(data)
    } catch {
      setError('Failed to load payslip data')
    } finally {
      setLoading(false)
    }
  }, [])

  useEffect(() => { load(monthYear) }, [load, monthYear])

  async function handleView(emp: PayslipSummary) {
    if (viewing) return
    setViewing(emp.employee_id)
    try {
      const [year, month] = monthYear.split('-').map(Number)
      // Look up the official Seawind salary slip PDF generated by the Accountant module.
      // Do NOT regenerate — open the stored PDF if it exists.
      const { data } = await payslipApi.getSlipUrl(emp.employee_id, month, year)
      if (data.found && data.file_url) {
        // Salary slip PDFs require ?employee_id= for the download auth check
        const sep = data.file_url.includes('?') ? '&' : '?'
        window.open(
          `${data.file_url}${sep}employee_id=${encodeURIComponent(emp.employee_id)}`,
          '_blank',
        )
      } else {
        // No generated PDF for this employee/month — mark the row
        setNotGenerated(prev => new Set([...prev, emp.employee_id]))
      }
    } catch {
      // On network error leave the button enabled for a retry
    } finally {
      setViewing(null)
    }
  }

  return (
    <div className="space-y-5">

      {/* Header */}
      <div className="flex items-start justify-between gap-4 flex-wrap">
        <div>
          <h1 className="text-xl font-bold text-gray-900">Payslips</h1>
          <p className="text-sm text-gray-500 mt-0.5">Pay slips with leave deduction breakdown for all employees</p>
        </div>
        <div className="flex items-center gap-2">
          <label className="text-[12px] font-semibold text-gray-500 shrink-0">Month</label>
          <input
            type="month"
            value={monthYear}
            onChange={e => setMonthYear(e.target.value)}
            max={defaultMonth}
            className="h-9 px-3 border-2 border-gray-200 rounded-xl text-[13px] bg-white focus:outline-none focus:border-indigo-400 transition-colors"
          />
        </div>
      </div>

      {error && (
        <div className="bg-red-50 border border-red-100 rounded-2xl px-5 py-4 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <i className="fa-solid fa-circle-exclamation text-red-400 text-[13px]" />
            <p className="text-[13px] text-red-600">{error}</p>
          </div>
          <button onClick={() => load(monthYear)} className="text-[12px] font-semibold text-red-500 hover:text-red-600">
            Retry
          </button>
        </div>
      )}

      {/* Summary cards */}
      {!loading && !error && rows.length > 0 && (() => {
        const totalGross        = rows.reduce((s, r) => s + r.monthly_salary, 0)
        const totalPT           = rows.reduce((s, r) => s + r.professional_tax, 0)
        const totalLeaveDeduct  = rows.reduce((s, r) => s + (r.unpaid_leave_deduction ?? 0), 0)
        const totalNet          = rows.reduce((s, r) => s + r.net_salary, 0)
        return (
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
            {[
              { label: 'Total Monthly Salary',   value: fmt(totalGross),       icon: 'fa-indian-rupee-sign', bg: 'bg-indigo-50', clr: 'text-indigo-600', border: 'border-indigo-100' },
              { label: 'Total PT Deduction',      value: fmt(totalPT),          icon: 'fa-minus-circle',      bg: 'bg-rose-50',   clr: 'text-rose-500',   border: 'border-rose-100' },
              { label: 'Total Leave Deduction',   value: fmt(totalLeaveDeduct), icon: 'fa-calendar-xmark',    bg: 'bg-amber-50',  clr: 'text-amber-600',  border: 'border-amber-100' },
              { label: 'Total Net Payable',       value: fmt(totalNet),         icon: 'fa-circle-check',      bg: 'bg-emerald-50',clr: 'text-emerald-600',border: 'border-emerald-100' },
            ].map(c => (
              <div key={c.label} className={`bg-white rounded-2xl border ${c.border} shadow-sm p-5 flex items-start gap-4`}>
                <div className={`w-9 h-9 rounded-xl ${c.bg} flex items-center justify-center shrink-0`}>
                  <i className={`fa-solid ${c.icon} ${c.clr} text-[14px]`} />
                </div>
                <div>
                  <p className="text-[10px] font-semibold text-gray-400 uppercase tracking-wide">{c.label}</p>
                  <p className="text-xl font-bold text-gray-900 mt-1">{c.value}</p>
                </div>
              </div>
            ))}
          </div>
        )
      })()}

      {/* Main table */}
      <div className="bg-white rounded-2xl border border-gray-100 shadow-sm overflow-hidden">
        <div className="px-5 py-3.5 border-b border-gray-50 flex items-center justify-between">
          <p className="text-[13px] font-semibold text-gray-800">Employee Pay Slips</p>
          {!loading && <p className="text-[11px] text-gray-400">{rows.length} employee{rows.length !== 1 ? 's' : ''}</p>}
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-[12px]">
            <thead>
              <tr className="bg-gray-50 border-b border-gray-100">
                {['Employee', 'Department', 'Job Title', 'Monthly Salary', 'Paid Leave', 'Unpaid Days', 'PT', 'Leave Deduction', 'Total Deductions', 'Net Payable', ''].map(h => (
                  <th key={h} className="text-left px-4 py-3 text-[10px] font-semibold uppercase tracking-wide text-gray-500 whitespace-nowrap">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {loading
                ? [...Array(5)].map((_, i) => (
                    <tr key={i} className="border-b border-gray-50">
                      <td className="px-4 py-3.5">
                        <div className="flex items-center gap-2.5 animate-pulse">
                          <div className="w-7 h-7 rounded-full bg-gray-200 shrink-0" />
                          <div className="h-3 w-24 bg-gray-200 rounded" />
                        </div>
                      </td>
                      {[...Array(9)].map((_, j) => (
                        <td key={j} className="px-4 py-3.5">
                          <div className="h-3 w-16 bg-gray-100 rounded animate-pulse" />
                        </td>
                      ))}
                    </tr>
                  ))
                : rows.length > 0
                  ? rows.map(r => (
                      <tr key={r.employee_id} className="border-b border-gray-50 last:border-0 hover:bg-gray-50/60 transition-colors">
                        <td className="px-4 py-3.5">
                          <div className="flex items-center gap-2">
                            <span className="w-7 h-7 rounded-full bg-indigo-100 text-indigo-700 text-[10px] font-bold flex items-center justify-center shrink-0">
                              {initials(r.employee_name)}
                            </span>
                            <div>
                              <p className="font-medium text-gray-800 leading-tight whitespace-nowrap">{r.employee_name}</p>
                              <p className="text-[10px] text-gray-400 font-mono">{r.employee_id}</p>
                            </div>
                          </div>
                        </td>
                        <td className="px-4 py-3.5 text-gray-600 whitespace-nowrap">{r.department}</td>
                        <td className="px-4 py-3.5 text-gray-600 whitespace-nowrap">{r.job_title}</td>
                        <td className="px-4 py-3.5 font-medium text-gray-700 whitespace-nowrap">{fmt(r.monthly_salary)}</td>
                        <td className="px-4 py-3.5 whitespace-nowrap">
                          {(r.paid_leave_used ?? 0) > 0
                            ? <span className="font-semibold text-emerald-600">{(r.paid_leave_used ?? 0).toFixed(1)}</span>
                            : <span className="text-gray-300">—</span>
                          }
                        </td>
                        <td className="px-4 py-3.5 whitespace-nowrap">
                          {(r.unpaid_leave_days ?? 0) > 0
                            ? <span className="font-semibold text-amber-600">{(r.unpaid_leave_days ?? 0).toFixed(1)}</span>
                            : <span className="text-gray-300">—</span>
                          }
                        </td>
                        <td className="px-4 py-3.5 text-red-500 whitespace-nowrap">{fmt(r.professional_tax)}</td>
                        <td className="px-4 py-3.5 whitespace-nowrap">
                          {(r.unpaid_leave_deduction ?? 0) > 0
                            ? <span className="font-semibold text-red-600">{fmt(r.unpaid_leave_deduction ?? 0)}</span>
                            : <span className="text-gray-300">—</span>
                          }
                        </td>
                        <td className="px-4 py-3.5 font-semibold text-red-700 whitespace-nowrap">
                          {fmt(r.professional_tax + (r.unpaid_leave_deduction ?? 0))}
                        </td>
                        <td className="px-4 py-3.5 font-bold text-indigo-700 whitespace-nowrap">{fmt(r.net_salary)}</td>
                        <td className="px-4 py-3.5">
                          {notGenerated.has(r.employee_id)
                            ? (
                              <span className="flex items-center gap-1 text-[11px] text-gray-400 italic whitespace-nowrap">
                                <i className="fa-solid fa-clock text-[10px]" />
                                Salary Slip Not Generated
                              </span>
                            ) : (
                              <button
                                onClick={() => handleView(r)}
                                disabled={viewing === r.employee_id || viewing !== null}
                                className="flex items-center gap-1 text-[11px] font-semibold text-indigo-600 bg-indigo-50 hover:bg-indigo-100 disabled:opacity-50 px-2.5 py-1.5 rounded-lg transition-colors whitespace-nowrap"
                              >
                                {viewing === r.employee_id
                                  ? <><i className="fa-solid fa-circle-notch animate-spin text-[10px]" /> Checking…</>
                                  : <><i className="fa-solid fa-file-pdf text-[10px]" /> View PDF</>
                                }
                              </button>
                            )
                          }
                        </td>
                      </tr>
                    ))
                  : (
                      <tr>
                        <td colSpan={11} className="px-5 py-8 text-center text-[13px] text-gray-400">
                          No employees found
                        </td>
                      </tr>
                    )
              }
            </tbody>
          </table>
        </div>
      </div>
    </div>
  )
}
